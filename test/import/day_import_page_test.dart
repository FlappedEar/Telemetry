/// A dated RaceChrono export without a start/finish line, starting at
/// [hour]:00 UTC on 2 October 2026.
String _datedVbo({required int hour, int speed = 72, int day = 2}) {
  final clock = hour.toString().padLeft(2, '0');
  final date = day.toString().padLeft(2, '0');
  final rows = StringBuffer();
  for (var i = 0; i < 5; ++i) {
    rows.write('${clock}000$i.000 3000.000000 -1200.000000 $speed\n');
  }
  return 'File created on $date/10/2026 at $clock:00:00\n'
      '[comments]\nGenerated by RaceChrono Pro v10.2.4\n'
      '[column names]\ntime latitude longitude velocity\n[data]\n$rows';
}

