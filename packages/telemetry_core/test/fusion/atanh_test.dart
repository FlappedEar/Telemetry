import 'package:telemetry_core/src/fusion/atanh.dart';
import 'package:test/test.dart';

// Expected values come from glibc 2.39's atanh and log1p (x86-64, generic
// build: GLIBC_TUNABLES=glibc.cpu.hwcaps=-AVX2,-FMA). The first atanh
// arguments are ones where both 0.5 * log((1 + x) / (1 - x)) and
// 0.5 * log1p(2x / (1 - x)) differ from it.
void main() {
  test('matches glibc atanh bit for bit', () {
    const cases = <(double, double)>[
      (-0.29543909231424692, -0.30451510064472787),
      (0.35419987553898302, 0.37023800504809651),
      (-0.38981721755001786, -0.41158448183438168),
      (0.14741075707952689, 0.14849263992284389),
      (-0.63000791999306927, -0.74142927632897959),
      (-0.8563131458875759, -1.2793556562655171),
      (-0.71135456948184839, -0.88992071547835594),
      (-0.3542595844895402, -0.37030628120180498),
      (-0.74568946381464229, -0.96317438056306381),
      (-0.54073110836977634, -0.60518823468321337),
      (-0.56486636849398053, -0.63995126450378026),
      (-0.034273239908699793, -0.034286669118693609),
      (-0.42318713125592922, -0.45156809894350924),
      (-0.82654017049179629, -1.1771163983888679),
      (0.091402829341076242, 0.091658653890556122),
      (-0.7558512946321656, -0.98646579928751454),
      (-0.51116738981085774, -0.56430880826498631),
      (-0.15755178455276564, -0.1588751641206369),
      (-0.2341141380335543, -0.23853777058505449),
      (0.099811065616114192, 0.10014450855878133),
      (-0.19980179764325356, -0.20252610178773089),
      (-0.40895454679318988, -0.43435516437723198),
      (-0.30050729987257085, -0.31007716989656464),
      (-0.2335631402974343, -0.23795490123810725),
      (0, 0),
      (-0, -0),
      (1e-10, 1e-10),
      (-3e-09, -3e-09),
      (0.25, 0.25541281188299536),
      (-0.5, -0.54930614433405478),
      (0.5, 0.54930614433405478),
      (0.75, 0.97295507452765662),
      (0.99999899999999997, 7.2543286192476693),
      (-0.99999899999999997, -7.2543286192476693),
      (0.99999999989999999, 11.859499013855018),
      (1e-300, 1e-300),
    ];
    for (final (x, expected) in cases) {
      expect(atanh(x), expected, reason: '$x');
    }
    expect(atanh(-0.0).isNegative, isTrue);
    expect(atanh(1.0), double.infinity);
    expect(atanh(-1.0), double.negativeInfinity);
    expect(atanh(1.5).isNaN, isTrue);
    expect(atanh(double.nan).isNaN, isTrue);
  });

  test('matches glibc log1p bit for bit', () {
    const cases = <(double, double)>[
      (-0.75, -1.3862943611198906),
      (-0.29999999999999999, -0.35667494393873234),
      (-0.28999999999999998, -0.3424903089467759),
      (0.10000000000000001, 0.095310179804324865),
      (0.40999999999999998, 0.34358970439007691),
      (0.41999999999999998, 0.35065687161316933),
      (1, 0.69314718055994529),
      (3.5, 1.5040773967762742),
      (100000, 11.512935464920229),
      (1e+20, 46.051701859880914),
      (1e-25, 1e-25),
      (-1e-10, -1.00000000005e-10),
    ];
    for (final (x, expected) in cases) {
      expect(log1p(x), expected, reason: '$x');
    }
    expect(log1p(-1.0), double.negativeInfinity);
    expect(log1p(-2.0).isNaN, isTrue);
    expect(log1p(double.infinity), double.infinity);
  });
}
